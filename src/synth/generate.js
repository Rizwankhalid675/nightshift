/**
 * generate.js — synthetic MSP alert traffic with ground truth.
 *
 * IMPORTANT (data policy): every alert this produces is invented. No customer,
 * employer or production data is used anywhere in this repository. The patterns
 * are the ones any MSP sees — a scheduled job that fails twice a day, a benign
 * log line emitted at ERROR, a flapping health check, maintenance noise, and a
 * genuine outage buried in all of it.
 *
 * Each alert carries a hidden `_truth` field. `stripTruth()` removes it before
 * anything in the pipeline sees it, so the evaluation can score the system
 * against labels the system was never shown. Seeded, so the README numbers
 * reproduce exactly on any machine.
 */

/** Deterministic PRNG (mulberry32). Same seed, same traffic, forever. */
export function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const iso = (ms) => new Date(ms).toISOString();

